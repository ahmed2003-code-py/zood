package com.zawed.api.fueling;

import java.time.Instant;
import java.util.Map;
import java.util.UUID;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Positive;
import jakarta.validation.constraints.Size;

import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.media.Schema.RequiredMode;

import com.zawed.api.fueling.Alerts.Alert;
import com.zawed.api.fueling.FuelingEngine.Result;
import com.zawed.api.fueling.FuelingEngine.WalletStatus;
import com.zawed.api.fueling.Fuelings.Fueling;
import com.zawed.api.fueling.Fuelings.Origin;
import com.zawed.api.fueling.Fuelings.Status;
import com.zawed.api.platform.FuelType;
import com.zawed.api.rules.FuelingRules.DeclineReason;

/** Request and response bodies of the fueling endpoints. */
final class FuelingApi {

	private FuelingApi() {
	}

	record PosFuelingRequest(
			@Schema(description = "Generated by the device once per fueling; a retry sends the same id") @NotNull UUID clientTxnId,
			@Schema(description = "The UID the reader returned, hex; spaces, colons and dashes are accepted") @NotBlank @Size(
					max = 64) String tagUid,
			@NotNull @Positive Long volumeMl,
			@Schema(description = "The fuel the agent selected; omitted means the vehicle's own") FuelType fuelType,
			@Schema(description = "Device time of the fueling") @NotNull Instant deviceAt,
			@NotNull @Pattern(regexp = "ar|en") String receiptLocale) {

		FuelingEngine.Request toRequest() {
			return new FuelingEngine.Request(clientTxnId, tagUid, volumeMl, fuelType, deviceAt, receiptLocale);
		}

	}

	/**
	 * What the POS shows and prints. The wallet is a status word, never an amount (PRD §6.1: the
	 * agent never sees the company's balance).
	 */
	record PosFuelingResponse(@Schema(requiredMode = RequiredMode.REQUIRED) UUID id,
			@Schema(requiredMode = RequiredMode.REQUIRED) String reference,
			@Schema(requiredMode = RequiredMode.REQUIRED) Status status, DeclineReason declineReason,
			@Schema(requiredMode = RequiredMode.REQUIRED) boolean replayed,
			@Schema(requiredMode = RequiredMode.REQUIRED) String plate,
			@Schema(requiredMode = RequiredMode.REQUIRED) String companyNameAr,
			@Schema(requiredMode = RequiredMode.REQUIRED) String companyNameEn,
			@Schema(requiredMode = RequiredMode.REQUIRED) String stationNameAr,
			@Schema(requiredMode = RequiredMode.REQUIRED) String stationNameEn,
			@Schema(requiredMode = RequiredMode.REQUIRED) String agentWorkerId,
			@Schema(requiredMode = RequiredMode.REQUIRED) FuelType fuelType,
			@Schema(requiredMode = RequiredMode.REQUIRED) long volumeMl,
			@Schema(requiredMode = RequiredMode.REQUIRED) long unitPricePiastres,
			@Schema(requiredMode = RequiredMode.REQUIRED) long amountPiastres,
			@Schema(requiredMode = RequiredMode.REQUIRED) boolean billable,
			@Schema(requiredMode = RequiredMode.REQUIRED) Instant evaluatedAt,
			@Schema(description = "Null on a replay") WalletStatus walletStatus,
			@Schema(description = "When the tag may fuel again; null on a replay") Instant cooldownUntil,
			@Schema(requiredMode = RequiredMode.REQUIRED) String receiptLocale,
			@Schema(requiredMode = RequiredMode.REQUIRED,
					description = "Path of the signed receipt link, under the API base") String receiptPath) {

		static PosFuelingResponse of(Result result, String receiptPath) {
			Fueling f = result.fueling();
			return new PosFuelingResponse(f.id(), f.reference(), f.status(), f.declineReason(), result.replayed(),
					f.plate(), f.companyNameAr(), f.companyNameEn(), f.stationNameAr(), f.stationNameEn(),
					f.agentWorkerId(), f.fuelType(), f.volumeMl(), f.unitPricePiastres(), f.amountPiastres(), f.billable(),
					f.evaluatedAt(), result.walletStatus(), result.cooldownUntil(), f.receiptLocale(), receiptPath);
		}

	}

	record FuelingResponse(@Schema(requiredMode = RequiredMode.REQUIRED) UUID id,
			@Schema(requiredMode = RequiredMode.REQUIRED) String reference,
			@Schema(requiredMode = RequiredMode.REQUIRED) Status status, DeclineReason declineReason,
			@Schema(requiredMode = RequiredMode.REQUIRED) Origin origin,
			@Schema(requiredMode = RequiredMode.REQUIRED) UUID companyId,
			@Schema(requiredMode = RequiredMode.REQUIRED) String companyNameAr,
			@Schema(requiredMode = RequiredMode.REQUIRED) String companyNameEn,
			@Schema(requiredMode = RequiredMode.REQUIRED) UUID vehicleId,
			@Schema(requiredMode = RequiredMode.REQUIRED) String plate,
			@Schema(requiredMode = RequiredMode.REQUIRED) UUID operatorId,
			@Schema(requiredMode = RequiredMode.REQUIRED) UUID stationId,
			@Schema(requiredMode = RequiredMode.REQUIRED) String stationNameAr,
			@Schema(requiredMode = RequiredMode.REQUIRED) String stationNameEn,
			@Schema(requiredMode = RequiredMode.REQUIRED) UUID deviceId,
			@Schema(requiredMode = RequiredMode.REQUIRED) String agentWorkerId,
			@Schema(requiredMode = RequiredMode.REQUIRED) FuelType fuelType,
			@Schema(requiredMode = RequiredMode.REQUIRED) long volumeMl,
			@Schema(requiredMode = RequiredMode.REQUIRED) long unitPricePiastres,
			@Schema(requiredMode = RequiredMode.REQUIRED) long amountPiastres,
			@Schema(requiredMode = RequiredMode.REQUIRED) boolean billable,
			@Schema(requiredMode = RequiredMode.REQUIRED) Instant evaluatedAt,
			@Schema(requiredMode = RequiredMode.REQUIRED) Instant deviceAt,
			@Schema(requiredMode = RequiredMode.REQUIRED) Instant receivedAt) {

		static FuelingResponse of(Fueling f) {
			return new FuelingResponse(f.id(), f.reference(), f.status(), f.declineReason(), f.origin(), f.companyId(),
					f.companyNameAr(), f.companyNameEn(), f.vehicleId(), f.plate(), f.operatorId(), f.stationId(),
					f.stationNameAr(), f.stationNameEn(), f.deviceId(), f.agentWorkerId(), f.fuelType(), f.volumeMl(),
					f.unitPricePiastres(), f.amountPiastres(), f.billable(), f.evaluatedAt(), f.deviceAt(),
					f.receivedAt());
		}

	}

	/** The printable receipt behind a signed link: no ids, nothing the bearer could use elsewhere. */
	record ReceiptResponse(@Schema(requiredMode = RequiredMode.REQUIRED) String reference,
			@Schema(requiredMode = RequiredMode.REQUIRED) Status status, DeclineReason declineReason,
			@Schema(requiredMode = RequiredMode.REQUIRED) String plate,
			@Schema(requiredMode = RequiredMode.REQUIRED) String companyNameAr,
			@Schema(requiredMode = RequiredMode.REQUIRED) String companyNameEn,
			@Schema(requiredMode = RequiredMode.REQUIRED) String stationNameAr,
			@Schema(requiredMode = RequiredMode.REQUIRED) String stationNameEn,
			@Schema(requiredMode = RequiredMode.REQUIRED) String agentWorkerId,
			@Schema(requiredMode = RequiredMode.REQUIRED) FuelType fuelType,
			@Schema(requiredMode = RequiredMode.REQUIRED) long volumeMl,
			@Schema(requiredMode = RequiredMode.REQUIRED) long unitPricePiastres,
			@Schema(requiredMode = RequiredMode.REQUIRED) long amountPiastres,
			@Schema(requiredMode = RequiredMode.REQUIRED) boolean billable,
			@Schema(requiredMode = RequiredMode.REQUIRED) Instant evaluatedAt,
			@Schema(requiredMode = RequiredMode.REQUIRED) String receiptLocale) {

		static ReceiptResponse of(Fueling f) {
			return new ReceiptResponse(f.reference(), f.status(), f.declineReason(), f.plate(), f.companyNameAr(),
					f.companyNameEn(), f.stationNameAr(), f.stationNameEn(), f.agentWorkerId(), f.fuelType(), f.volumeMl(),
					f.unitPricePiastres(), f.amountPiastres(), f.billable(), f.evaluatedAt(), f.receiptLocale());
		}

	}

	record AlertResponse(@Schema(requiredMode = RequiredMode.REQUIRED) UUID id,
			@Schema(requiredMode = RequiredMode.REQUIRED) Alerts.Type type,
			@Schema(requiredMode = RequiredMode.REQUIRED) Alerts.Severity severity,
			@Schema(requiredMode = RequiredMode.REQUIRED) Alerts.Status status, UUID companyId, UUID operatorId,
			UUID stationId, UUID vehicleId, UUID fuelingId,
			@Schema(requiredMode = RequiredMode.REQUIRED) Map<String, Object> details,
			@Schema(requiredMode = RequiredMode.REQUIRED) Instant createdAt, UUID acknowledgedBy,
			Instant acknowledgedAt) {

		static AlertResponse of(Alert a) {
			return new AlertResponse(a.id(), a.type(), a.severity(), a.status(), a.companyId(), a.operatorId(),
					a.stationId(), a.vehicleId(), a.fuelingId(), a.details(), a.createdAt(), a.acknowledgedBy(),
					a.acknowledgedAt());
		}

	}

}
