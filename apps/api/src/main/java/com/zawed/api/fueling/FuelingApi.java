	/** One fueling the device captured while offline (B5 contract §3). */
	record PosSyncItem(
			@Schema(description = "Generated by the device when the fueling was captured; the same id every time it is sent") @NotNull UUID clientTxnId,
			@Schema(description = "The UID the reader returned, hex; spaces, colons and dashes are accepted") @NotBlank @Size(
					max = 64) String tagUid,
			// A number, not a Long: one item's fraction must not refuse the whole batch (B5 §3). An integer
			// written as a float (20000.0) is that integer; a real fraction is this item's INVALID_VOLUME.
			@Schema(implementation = Long.class,
					description = "Whole millilitres, 1 ml to 1,500 L; outside that, or not a whole number, the item is REJECTED with INVALID_VOLUME") @NotNull BigDecimal volumeMl,
			@Schema(description = "The fuel the agent selected; omitted means the vehicle's own") FuelType fuelType,
			@Schema(description = "Device time of the fueling; the checks are judged at this instant") @NotNull Instant deviceAt,
			@Schema(description = "The agent who captured it; must have had a session on this device at deviceAt") @NotNull UUID agentId,
			@NotNull @Pattern(regexp = "ar|en") String receiptLocale,
			@Schema(implementation = Long.class,
					description = "The price per litre the terminal showed, whole piastres; a different server price is flagged PRICE_MISMATCH, a fraction rejects the item with VALIDATION_FAILED") BigDecimal unitPricePiastres) {

		FuelingEngine.OfflineRequest toRequest() {
			Long volume = whole(volumeMl);
			Long price = unitPricePiastres == null ? null : whole(unitPricePiastres);
			FuelingEngine.NotWhole notWhole = volume == null ? new FuelingEngine.NotWhole("volumeMl", volumeMl.toString())
					: unitPricePiastres != null && price == null
							? new FuelingEngine.NotWhole("unitPricePiastres", unitPricePiastres.toString()) : null;
			return new FuelingEngine.OfflineRequest(clientTxnId, tagUid, volume == null ? 0 : volume, fuelType, deviceAt,
					agentId, receiptLocale, price, notWhole);
		}

		/** The value as a long when it is a whole number that fits one, otherwise null. */
		private static Long whole(BigDecimal value) {
			try {
				return value.longValueExact();
			}
			catch (ArithmeticException ex) {
				return null;
			}
		}

	}

	record PosSyncRequest(
			@Schema(description = "The device's own id for this batch, shown in the sync monitor; sending a batch again is safe") @NotNull UUID batchId,
			@Schema(description = "How many captures the device still holds after this batch") @NotNull @PositiveOrZero Integer pending,
			@Schema(description = "At most 100, in capture order") @NotNull List<@NotNull @Valid PosSyncItem> items) {

		OfflineSync.Batch toBatch() {
			return new OfflineSync.Batch(batchId, pending, items.stream().map(PosSyncItem::toRequest).toList());
		}

	}

