package com.zawed.api.network;

import static com.zawed.api.platform.persistence.Sql.clean;
import static com.zawed.api.platform.persistence.Sql.instant;
import static com.zawed.api.platform.persistence.Sql.ts;

import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.Clock;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import org.springframework.dao.DuplicateKeyException;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import com.zawed.api.audit.AuditLog;
import com.zawed.api.network.Operators.Station;
import com.zawed.api.network.Operators.StationStatus;
import com.zawed.api.platform.crypto.PasswordHasher;
import com.zawed.api.platform.crypto.SecureTokens;
import com.zawed.api.platform.ids.IdGenerator;
import com.zawed.api.platform.security.Scope;
import com.zawed.api.platform.security.ZawedPrincipal;
import com.zawed.api.platform.web.ApiException;
import com.zawed.api.platform.web.Page;

/**
 * Station agents (PRD §6.1, §6.3). An agent signs in to the POS with a Worker ID and a 6-digit PIN.
 *
 * <p>A PIN has only a million values, so it is hashed with Argon2 like a password, generated by the
 * server (never chosen by Ops), shown once, and must be changed at first sign-in. Throttling and
 * lockout of PIN attempts belong to the device sign-in in B5.
 */
@Service
class Agents {

	enum AgentStatus {

		ACTIVE, SUSPENDED, DEACTIVATED

	}

	record Agent(UUID id, UUID operatorId, UUID stationId, String workerId, String fullName, String phone,
			AgentStatus status, boolean mustChangePin, Instant lockedUntil, Instant createdAt) {

		static Agent map(ResultSet rs, int row) throws SQLException {
			return new Agent(rs.getObject("id", UUID.class), rs.getObject("operator_id", UUID.class),
					rs.getObject("station_id", UUID.class), rs.getString("worker_id"), rs.getString("full_name"),
					rs.getString("phone"), AgentStatus.valueOf(rs.getString("status")),
					rs.getBoolean("must_change_pin"), instant(rs, "locked_until"), instant(rs, "created_at"));
		}

	}

	/** An agent with the PIN that was just generated. The PIN is not stored. */
	record WithPin(Agent agent, String pin) {
	}

	static final int PIN_LENGTH = 6;
	private static final int WORKER_ID_DIGITS = 7;
	private static final int ID_ATTEMPTS = 5;

	private final JdbcClient jdbc;
	private final Operators operators;
	private final PasswordHasher hasher;
	private final AuditLog audit;
	private final IdGenerator ids;
	private final Clock clock;

	Agents(JdbcClient jdbc, Operators operators, PasswordHasher hasher, AuditLog audit, IdGenerator ids, Clock clock) {
		this.jdbc = jdbc;
		this.operators = operators;
		this.hasher = hasher;
		this.audit = audit;
		this.ids = ids;
		this.clock = clock;
	}

	@Transactional(readOnly = true)
	Page<Agent> list(UUID operatorId, UUID stationId, AgentStatus status, String query, String cursor, Integer limit) {
		int size = Page.limit(limit);
		List<Agent> rows = jdbc.sql("""
				select * from agents
				where (cast(:operator as uuid) is null or operator_id = :operator)
				  and (cast(:station as uuid) is null or station_id = :station)
				  and (cast(:status as text) is null or status = :status)
				  and (cast(:q as text) is null or lower(full_name) like :q or worker_id = :raw)
				  and (cast(:cursor as uuid) is null or id < :cursor)
				order by id desc limit :limit
				""")
			.param("operator", operatorId)
			.param("station", stationId)
			.param("status", status == null ? null : status.name())
			.param("q", Operators.like(query))
			.param("raw", clean(query) == null ? null : clean(query).toUpperCase())
			.param("cursor", Page.cursor(cursor))
			.param("limit", size + 1)
			.query(Agent::map)
			.list();
		return Page.of(rows, size, Agent::id);
	}

	@Transactional(readOnly = true)
	Agent get(UUID id) {
		return jdbc.sql("select * from agents where id = :id")
			.param("id", id)
			.query(Agent::map)
			.optional()
			.orElseThrow(() -> ApiException.notFound("Agent"));
	}

	@Transactional
	WithPin create(ZawedPrincipal actor, UUID stationId, String fullName, String phone) {
		Station station = operators.lockStation(stationId);
		if (station.status() == StationStatus.CLOSED) {
			throw new ApiException(HttpStatus.CONFLICT, "STATION_CLOSED", "The station is closed");
		}
		String pin = newPin();
		UUID id = ids.next();
		Instant now = clock.instant();
		String workerId = null;
		for (int attempt = 0; attempt < ID_ATTEMPTS && workerId == null; attempt++) {
			String candidate = "W" + SecureTokens.digits(WORKER_ID_DIGITS);
			if (Boolean.FALSE.equals(jdbc.sql("select exists (select 1 from agents where worker_id = :w)")
				.param("w", candidate)
				.query(Boolean.class)
				.single())) {
				workerId = candidate;
			}
		}
		if (workerId == null) {
			throw new IllegalStateException("Could not generate a unique worker id");
		}
		try {
			jdbc.sql("""
					insert into agents (id, operator_id, station_id, worker_id, full_name, phone, pin_hash,
					                    must_change_pin, status, created_at, created_by, updated_at, updated_by)
					values (:id, :operator, :station, :worker, :name, :phone, :pin, true, 'ACTIVE', :now, :actor, :now,
					        :actor)
					""")
				.param("id", id)
				.param("operator", station.operatorId())
				.param("station", stationId)
				.param("worker", workerId)
				.param("name", clean(fullName))
				.param("phone", clean(phone))
				.param("pin", hasher.hash(pin))
				.param("now", ts(now))
				.param("actor", actor.userId())
				.update();
		}
		catch (DuplicateKeyException ex) {
			throw new ApiException(HttpStatus.CONFLICT, "CONCURRENT_CHANGE", "Try again");
		}
		audit.record(Operators.actorOf(actor), "AGENT_CREATED", "AGENT", id, Scope.operator(station.operatorId()),
				Map.of("workerId", workerId, "stationId", stationId.toString()));
		return new WithPin(get(id), pin);
	}

	/** A new PIN, shown once; clears any lockout and forces a change at the next sign-in. */
	@Transactional
	WithPin resetPin(ZawedPrincipal actor, UUID id) {
		Agent agent = lock(id);
		if (agent.status() == AgentStatus.DEACTIVATED) {
			throw deactivated();
		}
		String pin = newPin();
		jdbc.sql("""
				update agents set pin_hash = :pin, must_change_pin = true, failed_pin_count = 0, locked_until = null,
				       updated_at = :now, updated_by = :actor
				where id = :id
				""").param("id", id).param("pin", hasher.hash(pin)).param("now", ts(clock.instant()))
			.param("actor", actor.userId())
			.update();
		audit.record(Operators.actorOf(actor), "AGENT_PIN_RESET", "AGENT", id, Scope.operator(agent.operatorId()),
				Map.of());
		return new WithPin(get(id), pin);
	}

	@Transactional
	Agent setStatus(ZawedPrincipal actor, UUID id, AgentStatus status, String reason) {
		Agent agent = lock(id);
		if (agent.status() == status) {
			return agent;
		}
		if (agent.status() == AgentStatus.DEACTIVATED) {
			throw deactivated();
		}
		jdbc.sql("update agents set status = :status, updated_at = :now, updated_by = :actor where id = :id")
			.param("id", id)
			.param("status", status.name())
			.param("now", ts(clock.instant()))
			.param("actor", actor.userId())
			.update();
		audit.record(Operators.actorOf(actor), "AGENT_STATUS_CHANGED", "AGENT", id, Scope.operator(agent.operatorId()),
				Map.of("from", agent.status().name(), "to", status.name(), "reason", reason));
		return get(id);
	}

	/** A random PIN that is not one of the patterns people try first. */
	static String newPin() {
		while (true) {
			String pin = SecureTokens.digits(PIN_LENGTH);
			if (!isTrivial(pin)) {
				return pin;
			}
		}
	}

	/** All one digit, or a straight run up or down (123456, 987654). */
	static boolean isTrivial(String pin) {
		boolean same = true;
		boolean up = true;
		boolean down = true;
		for (int i = 1; i < pin.length(); i++) {
			int step = pin.charAt(i) - pin.charAt(i - 1);
			same &= step == 0;
			up &= step == 1;
			down &= step == -1;
		}
		return same || up || down;
	}

	private Agent lock(UUID id) {
		return jdbc.sql("select * from agents where id = :id for update")
			.param("id", id)
			.query(Agent::map)
			.optional()
			.orElseThrow(() -> ApiException.notFound("Agent"));
	}

	private static ApiException deactivated() {
		return new ApiException(HttpStatus.CONFLICT, "AGENT_DEACTIVATED", "The agent is deactivated");
	}

}
