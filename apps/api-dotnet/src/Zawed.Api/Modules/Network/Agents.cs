using Zawed.Api.Modules.Audit.Contracts;
using Zawed.Api.Platform.Crypto;
using Zawed.Api.Platform.Persistence;
using Zawed.Api.Platform.Security;
using Zawed.Api.Platform.Web;

namespace Zawed.Api.Modules.Network;

/// <summary>An agent with the PIN that was just generated. The PIN is not stored.</summary>
public sealed record AgentWithPin(AgentResponse Agent, string Pin);

/// <summary>
/// Station agents (PRD §6.1, §6.3; Java <c>network.Agents</c>). An agent signs in to the POS with a Worker ID and a
/// 6-digit PIN. A PIN has only a million values, so it is hashed with Argon2 like a password, generated by the server
/// (never chosen by Ops), shown once, and must be changed at first sign-in. Throttling and lockout of PIN attempts belong
/// to the device sign-in (<see cref="AgentSessions"/>).
/// </summary>
public sealed class Agents(IDbSession session, Operators operators, PasswordHasher hasher, IAuditLog audit, TimeProvider clock)
{
    public const int PinLength = 6;
    private const int WorkerIdDigits = 7;
    private const int IdAttempts = 5;

    private DbTx Tx => session.Current;

    public async Task<Result<Page<AgentResponse>>> ListAsync(Guid? operatorId, Guid? stationId, AgentStatus? status, string? query,
        string? cursor, int? limit, CancellationToken ct)
    {
        var size = Page<AgentResponse>.Limit(limit);
        var now = clock.GetUtcNow();
        var rows = (await Tx.QueryAsync<AgentRow>("""
            select * from agents
            where (cast(@operator as uuid) is null or operator_id = @operator)
              and (cast(@station as uuid) is null or station_id = @station)
              and (cast(@status as text) is null or status = @status)
              and (cast(@q as text) is null or lower(full_name) like @q or worker_id = @raw)
              and (cast(@cursor as uuid) is null or id < @cursor)
            order by id desc limit @limit
            """, new
        {
            @operator = operatorId, station = stationId, status = status?.ToString(), q = Operators.Like(query),
            raw = Sql.Clean(query) is { } searched ? Platform.Text.JavaText.ToUpperRoot(searched) : null, cursor = Cursors.Parse(cursor), limit = size + 1,
        }, ct)).Select(a => a.ToResponse(now)).ToList();
        return Page<AgentResponse>.Of(rows, size, a => a.Id);
    }

    public async Task<Result<AgentResponse>> GetAsync(Guid id, CancellationToken ct) =>
        await ReadAsync(id, ct) is { } row ? row.ToResponse(clock.GetUtcNow()) : Result<AgentResponse>.NotFound("Agent");

    public async Task<Result<AgentWithPin>> CreateAsync(ZawedPrincipal actor, Guid stationId, string fullName, string? phone, CancellationToken ct)
    {
        if (await operators.LockStationAsync(stationId, ct) is not { } station)
        {
            return Result<AgentWithPin>.NotFound("Station");
        }
        if (station.StationStatus == StationStatus.CLOSED)
        {
            return Result<AgentWithPin>.Conflict("STATION_CLOSED", "The station is closed");
        }
        var pin = NewPin();
        var now = clock.GetUtcNow();
        var id = Guid.CreateVersion7(now);
        string? workerId = null;
        for (var attempt = 0; attempt < IdAttempts && workerId is null; attempt++)
        {
            var candidate = "W" + SecureTokens.Digits(WorkerIdDigits);
            if (!await Tx.QuerySingleAsync<bool>("select exists (select 1 from agents where worker_id = @w)", new { w = candidate }, ct))
            {
                workerId = candidate;
            }
        }
        if (workerId is null)
        {
            throw new InvalidOperationException("Could not generate a unique worker id");
        }
        try
        {
            await Tx.ExecuteAsync("""
                insert into agents (id, operator_id, station_id, worker_id, full_name, phone, pin_hash,
                                    must_change_pin, status, created_at, created_by, updated_at, updated_by)
                values (@id, @operator, @station, @worker, @name, @phone, @pin, true, 'ACTIVE', @now, @actor, @now,
                        @actor)
                """, new
            {
                id, @operator = station.Operator_Id, station = stationId, worker = workerId, name = Sql.Clean(fullName),
                phone = Sql.Clean(phone), pin = hasher.Hash(pin), now, actor = actor.UserId,
            }, ct);
        }
        catch (Exception ex) when (DbErrors.IsUniqueViolation(ex))
        {
            return Result<AgentWithPin>.Conflict("CONCURRENT_CHANGE", "Try again");
        }
        await audit.RecordAsync(Tx, Rows.Actor(actor), "AGENT_CREATED", "AGENT", id, Scope.Operator(station.Operator_Id),
            new Dictionary<string, object?> { ["workerId"] = workerId, ["stationId"] = stationId.ToString() }, ct);
        return Result<AgentWithPin>.Created(new AgentWithPin((await ReadAsync(id, ct))!.ToResponse(clock.GetUtcNow()), pin));
    }

    /// <summary>A new PIN, shown once; clears any lockout and forces a change at the next sign-in.</summary>
    public async Task<Result<AgentWithPin>> ResetPinAsync(ZawedPrincipal actor, Guid id, CancellationToken ct)
    {
        if (await LockAsync(id, ct) is not { } agent)
        {
            return Result<AgentWithPin>.NotFound("Agent");
        }
        if (agent.AgentStatus == AgentStatus.DEACTIVATED)
        {
            return Deactivated<AgentWithPin>();
        }
        var pin = NewPin();
        await Tx.ExecuteAsync("""
            update agents set pin_hash = @pin, must_change_pin = true, failed_pin_count = 0, locked_until = null,
                   updated_at = @now, updated_by = @actor
            where id = @id
            """, new { id, pin = hasher.Hash(pin), now = clock.GetUtcNow(), actor = actor.UserId }, ct);
        // A reset means the old PIN may be known to someone else: its sessions end now (B4 review 6).
        var ended = await EndSessionsAsync(id, "PIN_RESET", ct);
        await audit.RecordAsync(Tx, Rows.Actor(actor), "AGENT_PIN_RESET", "AGENT", id, Scope.Operator(agent.Operator_Id),
            new Dictionary<string, object?> { ["sessionsEnded"] = ended }, ct);
        return new AgentWithPin((await ReadAsync(id, ct))!.ToResponse(clock.GetUtcNow()), pin);
    }

    public async Task<Result<AgentResponse>> SetStatusAsync(ZawedPrincipal actor, Guid id, AgentStatus status, string reason, CancellationToken ct)
    {
        if (await LockAsync(id, ct) is not { } agent)
        {
            return Result<AgentResponse>.NotFound("Agent");
        }
        if (agent.AgentStatus == status)
        {
            return agent.ToResponse(clock.GetUtcNow());
        }
        if (agent.AgentStatus == AgentStatus.DEACTIVATED)
        {
            return Deactivated<AgentResponse>();
        }
        await Tx.ExecuteAsync("update agents set status = @status, updated_at = @now, updated_by = @actor where id = @id",
            new { id, status = status.ToString(), now = clock.GetUtcNow(), actor = actor.UserId }, ct);
        // Suspended or deactivated: its sessions end, so a later reactivation does not revive them.
        var ended = status == AgentStatus.ACTIVE ? 0 : await EndSessionsAsync(id, "AGENT_" + status, ct);
        await audit.RecordAsync(Tx, Rows.Actor(actor), "AGENT_STATUS_CHANGED", "AGENT", id, Scope.Operator(agent.Operator_Id),
            new Dictionary<string, object?>
            {
                ["from"] = agent.Status, ["to"] = status.ToString(), ["reason"] = reason, ["sessionsEnded"] = ended,
            }, ct);
        return (await ReadAsync(id, ct))!.ToResponse(clock.GetUtcNow());
    }

    private Task<int> EndSessionsAsync(Guid agentId, string reason, CancellationToken ct) => Tx.ExecuteAsync("""
        update agent_sessions set revoked_at = @now, revoke_reason = @reason
        where agent_id = @agent and revoked_at is null
        """, new { agent = agentId, reason, now = clock.GetUtcNow() }, ct);

    /// <summary>A random PIN that is not one of the patterns people try first.</summary>
    public static string NewPin()
    {
        while (true)
        {
            var pin = SecureTokens.Digits(PinLength);
            if (!IsTrivial(pin))
            {
                return pin;
            }
        }
    }

    /// <summary>All one digit, or a straight run up or down (123456, 987654).</summary>
    public static bool IsTrivial(string pin)
    {
        bool same = true, up = true, down = true;
        for (var i = 1; i < pin.Length; i++)
        {
            var step = pin[i] - pin[i - 1];
            same &= step == 0;
            up &= step == 1;
            down &= step == -1;
        }
        return same || up || down;
    }

    private Task<AgentRow?> ReadAsync(Guid id, CancellationToken ct) =>
        Tx.QuerySingleOrDefaultAsync<AgentRow>("select * from agents where id = @id", new { id }, ct);

    private Task<AgentRow?> LockAsync(Guid id, CancellationToken ct) =>
        Tx.QuerySingleOrDefaultAsync<AgentRow>("select * from agents where id = @id for update", new { id }, ct);

    private static Result<T> Deactivated<T>() => Result<T>.Conflict("AGENT_DEACTIVATED", "The agent is deactivated");
}
